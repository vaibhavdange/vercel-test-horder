// Function to get image for a product
export function getProductImage(productName: string, categoryName: string): string | null {
  const categoryKey = categoryName.toLowerCase();
  const categoryImages = sampleImages[categoryKey as keyof typeof sampleImages];
  
  if (categoryImages) {
    // Try to find exact match first
    if (categoryImages[productName as keyof typeof categoryImages]) {
      return categoryImages[productName as keyof typeof categoryImages];
    }
    
    // Try to find partial match
    for (const [key, image] of Object.entries(categoryImages)) {
      if (productName.toLowerCase().includes(key.toLowerCase()) || 
          key.toLowerCase().includes(productName.toLowerCase())) {
        return image;
      }
    }
    
    // Return first image from category if no match found
    return Object.values(categoryImages)[0];
  }
  
  return null;
}

